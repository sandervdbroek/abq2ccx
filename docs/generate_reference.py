def md_table(headers, rows):
    out = ["| " + " | ".join(headers) + " |",
           "| " + " | ".join("---" for _ in headers) + " |"]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)


def element_category(t):
    checks = [
        (("SPRING", "DASHPOT", "GAPUNI", "GAPCYL", "GAPSPHER", "MASS", "DCOUP", "ROTARYI"), "discrete"),
        (("COH",), "cohesive"),
        (("CONN", "JOINTC"), "connector"),
        (("R3D", "RB2", "RB3", "RAX", "R2D"), "rigid"),
        (("SFM",), "surface (load carrier)"),
        (("DC3D", "DC1D"), "heat-transfer continuum"),
        (("C3D",), "3D continuum"),
        (("F3D",), "3D fluid (CFD)"),
        (("M3D",), "membrane"),
        (("CPS",), "plane stress"),
        (("CPEG",), "generalized plane strain"),
        (("CPE",), "plane strain"),
        (("CGAX",), "generalized axisymmetric"),
        (("CAX",), "axisymmetric"),
        (("STRI", "SC", "DS", "US", "S"), "shell"),
        (("PIPE", "T2D", "T3D", "B"), "beam / truss"),
    ]
    if t == "D":
        return "fluid/network"
    for prefixes, name in checks:
        if t.startswith(prefixes):
            return name
    return "other"


def element_status(t):
    own = _element_status(t)
    twin = A.ONE_POINT_TWIN.get(A.ccx_element_type(t, A.Report()))
    if twin and t not in A.SURFACE_ELEMENTS:
        own += (" — in ccx 2.23 one `C3D8R` brick whose hourglass stiffness alone bends it: reduced "
                + ("physics" if twin in ("M3D4", "B31") else "physics where its elements are over 3 "
                   "depths wide (1.5 if plastic)") + f"; `--approximate` → `{twin}`")
    ct = A.ccx_element_type(t, A.Report())
    if A.plane_locks(t) and t not in A.SLAB_TYPES:
        own += (" — locks in plastic flow (ccx 2.23 has no selectively reduced volume terms): reduced "
                f"physics with a plastic material; `--approximate` → `{A.PLANE_QUADRATIC_UPGRADE[ct[:3]][1]}`")
    return own


def _element_status(t):
    if t in A.SURFACE_ELEMENTS:
        return "left out of the mesh; its loads → consistent nodal forces"
    if t in A.SLAB_TYPES:
        return (f"→ `C3D8I` slab (exact for small-strain linear elasticity in static steps); otherwise → "
                f"`{A.ccx_element_type(t, A.Report())}`, reduced physics")
    if t in A.PLY_SOLID:
        return (f"→ `{A.ccx_element_type(t, A.Report())}` (substituted: reduced physics); under a "
                f"composite section one `{A.PLY_SOLID[t]}` per ply")
    if t in A.QUAD_MEMBRANE_SOLID:
        return (f"→ `{A.QUAD_MEMBRANE_SOLID[t]}` on nodes of its own, held at the membrane's nodes "
                + ("(exact)" if t in A.CCX_ELEMENTS else "without its centre node (reduced physics)"))
    up = A.COMPOSITE_SHELL_UPGRADE.get(A.ccx_element_type(t, A.Report()))
    if up:
        own = "direct" if t in A.CCX_ELEMENTS else (
            f"→ `{A.ccx_element_type(t, A.Report())}` (exact)" if t in A.EXACT_SUBSTITUTIONS else
            f"→ `{A.ccx_element_type(t, A.Report())}` (substituted: reduced physics)")
        if A.ccx_element_type(t, A.Report()) == "S4R":
            own += (" — in ccx 2.23 bends only through its `C3D8R`'s hourglass stiffness (reduced "
                    "physics; `--approximate` → `S4`, `S8R` where coarse)")
        return f"{own}; under a composite section → `{up}` with midside nodes (reduced physics)"
    if t == "DASHPOT2":
        return ("→ `DASHPOTA` to a new node that `*EQUATION`s move with the second node's DOF along the "
                "first DOF's line (exact, also under `NLGEOM`); on a rotational DOF left out (reduced physics)")
    if t in ("SPRING1", "SPRING2"):
        return "direct; at a node with a `*TRANSFORM` on a new node tied to its local DOF (exact)"
    if t in A.EXACT_SUBSTITUTIONS:
        return f"→ `{A.ccx_element_type(t, A.Report())}` (exact)"
    if t in A.ELEMENT_TYPE_MAP:
        return f"→ `{A.ccx_element_type(t, A.Report())}` (substituted: reduced physics)"
    if t in A.CCX_ELEMENTS:
        return "direct"
    if t.endswith("H") and t[:-1] in A.CCX_ELEMENTS:
        return f"→ `{t[:-1]}` (hybrid dropped: reduced physics)"
    if t in ("R3D3", "R3D4"):
        return f"→ `{'C3D6' if t == 'R3D3' else 'C3D8'}` skin of its rigid body (exact; face `S2` = `SPOS`, `S1` = `SNEG`)"
    if t in ("R2D2", "RB2D2"):
        return "→ `C3D8` skin through the model's thickness, 3-D rigid body held in the plane (exact; `S5` / `S3`)"
    if t == "RAX2":
        return "→ `C3D8` skin over ccx's ±1° sector, 3-D rigid body held in the plane (exact; `S5` / `S3`)"
    if t == "RB3D2":
        return "not emitted — its nodes join its rigid body"
    if t == "ROTARYI":
        return "on a rigid body with a `*MASS`: six point masses (exact); otherwise flagged"
    if t in A.CONN_TYPES:
        return "not emitted — its `*CONNECTOR SECTION` becomes ccx constraints, springs and dashpots"
    if t == "JOINTC":
        return ("not emitted — its `*JOINT`'s linear `*SPRING` / `*DASHPOT` options become springs and "
                "dashpots on its six relative components (as a connector's)")
    if t == "DASHPOT1":
        return ("→ `DASHPOTA` to a new ground node that `*EQUATION`s keep on its DOF's line (exact, "
                "also under `NLGEOM`); on a rotational DOF left out (reduced physics)")
    if t.startswith(A.UNSUPPORTED_ELEM_PREFIXES):
        return "flagged — no ccx equivalent"
    return "passed through (verify)"


