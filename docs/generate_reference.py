def md_table(headers, rows):
    out = ["| " + " | ".join(headers) + " |",
           "| " + " | ".join("---" for _ in headers) + " |"]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)


def element_category(t):
    checks = [
        (("SPRING", "DASHPOT", "GAPUNI", "GAPCYL", "GAPSPHER", "MASS", "DCOUP", "ROTARYI"), "discrete"),
        (("COH",), "cohesive"),
        (("CONN",), "connector"),
        (("R3D", "RB2", "RB3", "RAX"), "rigid"),
        (("DC3D", "DC1D"), "heat-transfer continuum"),
        (("C3D",), "3D continuum"),
        (("F3D",), "3D fluid (CFD)"),
        (("M3D",), "membrane"),
        (("CPS",), "plane stress"),
        (("CPEG",), "generalized plane strain"),
        (("CPE",), "plane strain"),
        (("CGAX",), "generalized axisymmetric"),
        (("CAX",), "axisymmetric"),
        (("STRI", "SC", "DS", "US", "S"), "shell"),
        (("PIPE", "T2D", "T3D", "B"), "beam / truss"),
    ]
    if t == "D":
        return "fluid/network"
    for prefixes, name in checks:
        if t.startswith(prefixes):
            return name
    return "other"


def element_status(t):
    if t in A.ELEMENT_TYPE_MAP:
        return f"→ `{A.ccx_element_type(t, A.Report())}` (substituted)"
    if t in A.CCX_ELEMENTS:
        return "direct"
    if t.endswith("H") and t[:-1] in A.CCX_ELEMENTS:
        return f"→ `{t[:-1]}` (hybrid)"
    if t.startswith(("R3D", "RB2", "RB3", "RAX")):
        return "flagged → model as `*RIGID BODY`"
    if t.startswith(A.UNSUPPORTED_ELEM_PREFIXES):
        return "flagged — no ccx equivalent"
    return "passed through (verify)"


def gen_elements():
    cats = {}
    for t in sorted(A.ELEMENT_NNODES):
        cats.setdefault(element_category(t), []).append(t)
    parts = [AUTOGEN, "# Element reference\n",
             "Every Abaqus element type the converter recognises, its node count, and how it is "
             "emitted for CalculiX. **Substitutions preserve the node count** so connectivity stays "
             "valid. Solid/shell node *ordering* is identical between the two codes, so connectivity "
             "is passed through unchanged.\n",
             f"Direct CalculiX types: **{len(A.CCX_ELEMENTS)}**. Total recognised: "
             f"**{len(A.ELEMENT_NNODES)}**.\n"]
    for cat in sorted(cats):
        rows = [(f"`{t}`", A.ELEMENT_NNODES[t], element_status(t)) for t in cats[cat]]
        parts.append(f"## {cat}\n")
        parts.append(md_table(["Abaqus type", "Nodes", "CalculiX"], rows) + "\n")
        if cat == "beam / truss":
            pairs = ", ".join(f"`{a}` → `{b}`" for a, b in A.CIRC_QUADRATIC.items())
            parts.append("Under a `*BEAM SECTION, SECTION=CIRC`, 2-node beams whose emitted type is "
                         f"{pairs} become 3-node beams: ccx 2.23 rejects linear beams with a "
                         "circular section. Each element gets a new midside node at the midpoint of "
                         "its end nodes (ccx's order is end, middle, end); element ids and sets are "
                         "kept, and BCs, temperatures and initial conditions given for both end "
                         "nodes also reach the midside node.\n")
            b32r = ", ".join(f"`{a}`" for a in A.PIPE_BOX_B32R)
            parts.append("Under `SECTION=PIPE`, `BOX` or `THICK PIPE` (emitted as `PIPE`), which ccx "
                         f"2.23 runs only on `B32R`, beams whose emitted type is {b32r} become `B32R`: "
                         "the 2-node ones get a midside node in the same way, and `B32` only changes "
                         "type.\n")
            planar = ", ".join(f"`{t}`" for t in sorted(A.PLANAR_LINE_TYPES))
            parts.append("ccx has no planar beam or truss — it runs `B21` as `B31` and `T2D2` as "
                         f"`T3D2` — so the out-of-plane DOFs of {planar} (and their `H`/`T` variants) "
                         "are free in ccx. In a planar model (no 3-D elements, all their nodes at one "
                         "z) the converter fixes DOF 3 on their nodes, midside nodes included (node set "
                         f"`{A.PLANAR_NODES_SET}`, model data, repeated after `*BOUNDARY, OP=NEW`), and "
                         "DOFs 4-5 at one node of a straight beam whose twist nothing restrains (on a "
                         "circular section, an element's middle node: at an end node ccx 2.23 would "
                         "lock the bending rotation too). The "
                         "rotations are not fixed on every node (that stiffens ccx's expanded beams), so "
                         "`*FREQUENCY` results include twist modes that Abaqus' planar beams do not "
                         "have (warned).\n")
    return "\n".join(parts)


def gen_keywords():
    handled = {"NODE", "ELEMENT", "NSET", "ELSET", "NGEN", "NFILL", "NCOPY", "NMAP", "ELGEN",
               "ELCOPY", "ELASTIC", "ORIENTATION", "DISTRIBUTION", "SOLID SECTION", "SHELL SECTION",
               "BEAM SECTION", "STEP", "END STEP", "BOUNDARY", "DLOAD", "DSLOAD", "TIE", "MPC",
               "CREEP", "AMPLITUDE", "RESTART", "SURFACE", "OUTPUT", "NODE OUTPUT", "ELEMENT OUTPUT",
               "NODE FILE", "EL FILE", "NODE PRINT", "EL PRINT", "STATIC", "DYNAMIC", "FREQUENCY",
               "BUCKLE", "HEAT TRANSFER", "EQUATION", "COUPLING", "KINEMATIC", "RIGID BODY",
               "CONTACT PAIR", "SURFACE INTERACTION", "FRICTION", "PLASTIC", "DENSITY",
               "SPECIFIC HEAT", "CONDUCTIVITY", "EXPANSION", "MOHR COULOMB",
               "MOHR COULOMB HARDENING", "HYPERELASTIC", "DEPVAR", "INITIAL CONDITIONS", "CLOAD",
               "CONTACT OUTPUT", "CONTACT FILE"}
    supported = sorted(k for k in A.CCX_KEYWORDS
                       if k not in handled and k not in A.PASS_WITH_NOTE and k not in A.SEMANTIC_TRAP)
    parts = [AUTOGEN, "# Keyword reference\n",
             "How each Abaqus keyword is handled. The converter knows the complete CalculiX 2.22 + 2.23 "
             f"keyword set (**{len(A.CCX_KEYWORDS)}** cards). Anything in that set is emitted as-is; "
             "anything outside it without a translator is commented out with guidance — never "
             "silently dropped.\n",
             "## Translated / converted to an equivalent\n",
             md_table(["Abaqus keyword", "Handling"],
                      [(f"`{k}`", v) for k, v in TRANSLATED.items()]) + "\n",
             "## Supported — emitted unchanged\n",
             "CalculiX accepts these as-is (verified against the ccx 2.22 manual):\n",
             ", ".join(f"`*{k}`" for k in supported) + "\n",
             "## Passed through with a heads-up\n",
             md_table(["Keyword", "Note"], [(f"`*{k}`", v) for k, v in A.PASS_WITH_NOTE.items()]) + "\n",
             "## Same name, different meaning (warned)\n",
             md_table(["Keyword", "Warning"], [(f"`*{k}`", v) for k, v in A.SEMANTIC_TRAP.items()]) + "\n",
             "## Dropped — organisational, no ccx meaning\n",
             "Silently dropped (with a note): "
             + ", ".join(f"`*{k}`" for k in sorted(A.DROP_KEYWORDS)) + ".\n",
             "Dropped with a warning (can change the model):\n",
             md_table(["Keyword", "Warning"],
                      [(f"`*{k}`", v) for k, v in A.DROP_WARN_KEYWORDS.items()]) + "\n",
             "## No CalculiX equivalent — commented out with guidance\n",
             "Any keyword not in the CalculiX set and without a translator is emitted as `**` "
             "comments plus a warning. These have tailored guidance:\n",
             md_table(["Keyword", "Guidance"],
                      [(f"`*{k}`", v) for k, v in A.SPECIAL_UNSUPPORTED.items()]) + "\n"]
    return "\n".join(parts)


def gen_output():
    parts = [AUTOGEN, "# Output-variable reference\n",
             "How Abaqus field/history output identifiers map to CalculiX `*NODE FILE` / "
             "`*EL FILE` / `*NODE PRINT` / `*EL PRINT` variables.\n",
             "## Renamed / folded onto a CalculiX identifier\n",
             md_table(["Abaqus", "CalculiX"],
                      [(f"`{a}`", f"`{c}`") for a, c in sorted(A.ABQ_MAP_VARS.items())]) + "\n",
             "## Dropped — no CalculiX equivalent (derive in post-processing)\n",
             ", ".join(f"`{v}`" for v in sorted(A.ABQ_DROP_VARS)) + "\n",
             "## Valid only on `*EL PRINT` / `*NODE PRINT` (.dat)\n",
             "Dropped from `*EL FILE`/`*NODE FILE` (.frd): "
             + ", ".join(f"`{v}`" for v in sorted(A.EL_PRINT_ONLY_VARS)) + ".\n"]
    return "\n".join(parts)


def main():
    for name, text in [("keyword-reference.md", gen_keywords()),
                       ("element-reference.md", gen_elements()),
                       ("output-reference.md", gen_output())]:
        with open(os.path.join(HERE, name), "w") as fh:
            fh.write(text.rstrip() + "\n")
        print("wrote", os.path.join("docs", name))


if __name__ == "__main__":
    main()
